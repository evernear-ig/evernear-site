// Generador de fechas relativas al inicio de la semana actual (Lunes)
const mondayThisWeek = getWeekStart();

const dateInCurrentWeek = (dayOffset: number, hour = 11) => {
  const d = new Date(mondayThisWeek);
  d.setDate(d.getDate() + dayOffset);
  d.setHours(hour, 30, 0, 0);
  return d.toISOString();
};

const dateInPastWeek = (weeksAgo: number, dayOffset: number, hour = 14) => {
  const d = new Date(mondayThisWeek);
  d.setDate(d.getDate() - weeksAgo * 7 + dayOffset);
  d.setHours(hour, 0, 0, 0);
  return d.toISOString();
};

